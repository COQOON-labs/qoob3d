// ADR-0039: one commit changes either tests or production code.
#[test]
fn rejects_tests_mixed_with_code() {
    let mixed = files(&[
        ("M", "crates/qoob3d-core/src/expr.rs"),
        ("A", "crates/qoob3d-core/src/expr/tests.rs"),
    ]);
    let problems = check_files(&mixed, "Add expr");
    assert_eq!(problems.len(), 1, "{problems:?}");
    assert!(
        problems[0].contains("changes tests and production code together (ADR-0039)")
            && problems[0].contains("`Mixed-Change: <reason>` trailer"),
        "{problems:?}"
    );
    let with_oracle =
        files(&[("M", "models/gear.expect.json"), ("M", "crates/qoob3d-core/src/gear.rs")]);
    assert!(!check_files(&with_oracle, "Change gear").is_empty());
}

// ADR-0039: a `Mixed-Change:` line allows mixing; it must start the line.
#[test]
fn mixed_change_trailer_allows_mixing() {
    let mixed = files(&[
        ("M", "crates/qoob3d-core/src/expr.rs"),
        ("M", "crates/qoob3d-core/tests/expr.rs"),
    ]);
    let message = "Rename eval\n\nMixed-Change: API rename with all callers\n";
    assert!(check_files(&mixed, message).is_empty());
    let mid_line = "Rename eval\n\nno Mixed-Change: here\n";
    assert!(!check_files(&mixed, mid_line).is_empty());
}

// ADR-0039: docs and other files may accompany either tests or code.
#[test]
fn other_files_mix_with_anything() {
    for pairs in [
        &[("M", "crates/qoob3d-core/src/expr.rs"), ("M", "docs/architecture.md")][..],
        &[("A", "crates/qoob3d-core/tests/expr.rs"), ("M", "docs/requirements/sketches.md")][..],
        &[("M", "crates/qoob3d-core/src/expr.rs"), ("M", "crates/qoob3d-core/Cargo.toml")][..],
        &[("M", "crates/qoob3d-core/tests/a.rs"), ("M", "crates/qoob3d-core/tests/b.rs")][..],
        &[][..],
    ] {
        assert!(check_files(&files(pairs), "Change").is_empty(), "{pairs:?}");
    }
}

// ADR-0030/ADR-0039: fixtures may only be added; every other status is one
// problem per file, and `Mixed-Change` does not excuse it.
#[test]
fn fixtures_may_only_be_added() {
    let fixture = "crates/qoob3d-core/tests/fixtures/v1.qbd";
    assert!(check_files(&files(&[("A", fixture)]), "Add fixture").is_empty());
    for status in ["M", "D", "R100", "R087"] {
        let problems = check_files(&files(&[(status, fixture)]), "x");
        assert_eq!(problems.len(), 1, "{status}");
        let expected = format!("fixture {fixture} modified/deleted \u{2013} forbidden (ADR-0030)");
        assert!(problems[0].contains(&expected), "{problems:?}");
    }
    let two = files(&[("M", fixture), ("D", "crates/qoob3d-core/tests/fixtures/v2.qbd")]);
    assert_eq!(check_files(&two, "x").len(), 2);
    let excused = "x\n\nMixed-Change: reason\n";
    assert_eq!(check_files(&files(&[("M", fixture)]), excused).len(), 1);
}

// ADR-0039: `git diff-tree --name-status` lines become (status, path) pairs,
// a rename contributes both paths.
#[test]
fn parses_name_status() {
    let listing = "M\tcrates/a.rs\nA\tdocs/b.md\nD\tc.rs\nR100\told.rs\tnew.rs\n";
    assert_eq!(
        parse_name_status(listing),
        files(&[
            ("M", "crates/a.rs"),
            ("A", "docs/b.md"),
            ("D", "c.rs"),
            ("R100", "old.rs"),
            ("R100", "new.rs")
        ])
    );
    assert!(parse_name_status("").is_empty());
}

// ADR-0030/ADR-0039: renaming a fixture away is caught via both parsed paths.
#[test]
fn renamed_fixture_is_rejected() {
    let listing = "R100\tcrates/qoob3d-core/tests/fixtures/v1.qbd\tdocs/v1.qbd\n";
    assert_eq!(check_files(&parse_name_status(listing), "Move").len(), 1);
}

// ADR-0044 (spec section 2): the first line that is neither empty nor a `#`
// comment, trimmed, is the allowed identity.
#[test]
fn allowed_identity_is_first_non_comment_line() {
    let text = "# The only identity.\n# Second comment.\n\n   \n  Jane Doe <jane@example.com>  \n\
                Other Person <other@example.com>\n";
    assert_eq!(allowed_identity(text), Some("Jane Doe <jane@example.com>".to_owned()));
    assert_eq!(
        allowed_identity("Jane Doe <jane@example.com>"),
        Some("Jane Doe <jane@example.com>".to_owned())
    );
    for text in ["", "\n\n", "# only a comment\n", "# a\n   \n# b\n"] {
        assert_eq!(allowed_identity(text), None, "{text:?}");
    }
}

// ADR-0044 (spec section 2): the repository file names the project identity.
#[test]
fn repository_identity_file_names_the_owner() {
    assert_eq!(IDENTITY_FILE, "harness/identity.txt");
    let text = include_str!("../../../harness/identity.txt");
    assert_eq!(allowed_identity(text), Some(ALLOWED.to_owned()));
}

// ADR-0044 (spec section 2): the exact allowed identity passes, also with
// surrounding whitespace (compared after trimming).
#[test]
fn project_identity_passes() {
    for role in ["author", "committer"] {
        assert!(check_identity(role, ALLOWED, ALLOWED).is_empty(), "{role}");
        let padded = format!("  {ALLOWED} ");
        assert!(check_identity(role, &padded, ALLOWED).is_empty(), "{role}");
    }
}

// ADR-0044 (spec section 2): any other identity, also with the same name or
// the same mail, is one problem naming role, identity and allowed identity.
#[test]
fn other_identities_are_rejected() {
    for identity in [
        "Jane Doe <jane@example.com>",
        "Benjamin Gr\u{f6}ner <bgroener-at-porsche@example.com>",
        "Ben-Gee <bgroener@coqoon.com>",
        "Benjamin Groener <bgroener@coqoon.com>",
        "benjamin gr\u{f6}ner <bgroener@coqoon.com>",
        "",
    ] {
        let problems = check_identity("author", identity, ALLOWED);
        assert_eq!(problems.len(), 1, "{identity:?}: {problems:?}");
        let expected = format!(
            "author `{identity}` is not the project identity `{ALLOWED}` \
             (harness/identity.txt, ADR-0044)"
        );
        assert!(problems[0].contains(&expected), "{problems:?}");
    }
}

// ADR-0038/ADR-0044 (spec section 2): an AI identity is "an AI tool" and, if it
// differs from the allowed one, also "not the project identity".
#[test]
fn ai_identities_are_rejected() {
    let identity = "Claude <noreply@anthropic.com>";
    let problems = check_identity("committer", identity, ALLOWED);
    assert_eq!(problems.len(), 2, "{problems:?}");
    assert!(
        problems
            .iter()
            .any(|p| p.contains("committer `Claude <noreply@anthropic.com>` is an AI tool")),
        "{problems:?}"
    );
    assert!(problems.iter().any(|p| p.contains("is not the project identity")), "{problems:?}");
    // Even an allowed identity that names an AI tool is rejected as one.
    let bot = "Copilot Bot <bot@example.com>";
    let problems = check_identity("author", bot, bot);
    assert_eq!(problems.len(), 1, "{problems:?}");
    assert!(problems[0].contains("author `Copilot Bot <bot@example.com>` is an AI tool"));
}

// ADR-0044 (spec section 2): `git var GIT_AUTHOR_IDENT` output → `Name <mail>`.
#[test]
fn ident_name_email_strips_timestamp() {
    assert_eq!(ident_name_email("Name <mail> 1700000000 +0200"), "Name <mail>");
    assert_eq!(ident_name_email(&format!("{ALLOWED} 1760400000 -0700")), ALLOWED);
    assert_eq!(
        ident_name_email("Jane Q. Doe <jane@example.com> 1 +0000"),
        "Jane Q. Doe <jane@example.com>"
    );
}

/// A temporary git repository with hooks and signing switched off.
fn git_repo(test: &str) -> PathBuf {
    let root = std::env::temp_dir().join(format!("qoob3d-commits-{test}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(&root).unwrap();
    git_in(&root, &[], &["init", "-q", "-b", "main"]);
    root
}

/// Runs git in `root` without global/system config, hooks or signing.
fn git_in(root: &Path, env: &[(&str, &str)], args: &[&str]) {
    let status = Command::new("git")
        .args(["-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null"])
        .args(args)
        .current_dir(root)
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .envs(env.iter().copied())
        .status()
        .unwrap();
    assert!(status.success(), "git {args:?}");
}

fn commit_as(root: &Path, file: &str, author: (&str, &str), committer: (&str, &str)) {
    fs::write(root.join(file), file).unwrap();
    git_in(root, &[], &["add", "-A"]);
    let env = [
        ("GIT_AUTHOR_NAME", author.0),
        ("GIT_AUTHOR_EMAIL", author.1),
        ("GIT_COMMITTER_NAME", committer.0),
        ("GIT_COMMITTER_EMAIL", committer.1),
    ];
    git_in(root, &env, &["commit", "-q", "-m", &format!("Add {file}")]);
}

// ADR-0044 (spec section 2): `check_range` checks author and committer of every
// commit against `harness/identity.txt`.
#[test]
fn check_range_rejects_foreign_author_and_committer() {
    let root = git_repo("range");
    fs::create_dir_all(root.join("harness")).unwrap();
    fs::write(root.join(IDENTITY_FILE), "# comment\nAlice <alice@example.com>\n").unwrap();
    let alice = ("Alice", "alice@example.com");
    let bob = ("Bob", "bob@example.com");
    commit_as(&root, "a.md", alice, alice);
    assert_eq!(check_range(&root, &["HEAD".to_owned()]), Ok(()));

    commit_as(&root, "b.md", bob, alice);
    commit_as(&root, "c.md", alice, bob);
    let problems = check_range(&root, &["HEAD".to_owned()]).unwrap_err();
    assert_eq!(problems.len(), 2, "{problems:?}");
    assert!(
        problems.iter().all(|p| p.contains("`Bob <bob@example.com>` is not the project identity")),
        "{problems:?}"
    );
    assert!(problems.iter().any(|p| p.contains("author")), "{problems:?}");
    assert!(problems.iter().any(|p| p.contains("committer")), "{problems:?}");
    fs::remove_dir_all(&root).unwrap();
}

// ADR-0044 (spec section 2): without an identity line the range fails with one
// problem naming the file.
#[test]
fn check_range_without_identity_file_fails() {
    let root = git_repo("range_no_identity");
    let alice = ("Alice", "alice@example.com");
    commit_as(&root, "a.md", alice, alice);
    let problems = check_range(&root, &["HEAD".to_owned()]).unwrap_err();
    assert!(
        problems.iter().any(|p| p.contains("harness/identity.txt: no allowed identity")),
        "{problems:?}"
    );
    fs::create_dir_all(root.join("harness")).unwrap();
    fs::write(root.join(IDENTITY_FILE), "# only comments\n\n").unwrap();
    let problems = check_range(&root, &["HEAD".to_owned()]).unwrap_err();
    assert!(
        problems.iter().any(|p| p.contains("harness/identity.txt: no allowed identity")),
        "{problems:?}"
    );
    fs::remove_dir_all(&root).unwrap();
}
