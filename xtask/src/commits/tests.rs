/// The identity in `harness/identity.txt` (spec section 2, ADR-0044).
const ALLOWED: &str = "Benjamin Gr\u{f6}ner <bgroener@coqoon.com>";

fn files(pairs: &[(&str, &str)]) -> Vec<(String, String)> {
    pairs.iter().map(|(s, p)| ((*s).to_owned(), (*p).to_owned())).collect()
}

// ADR-0038: a `…-by:` trailer naming an AI tool is rejected, case-insensitively.
#[test]
fn rejects_ai_trailers() {
    for line in [
        "Co-Authored-By: Claude Opus <noreply@anthropic.com>",
        "co-authored-by: GitHub Copilot <x@users.noreply.github.com>",
        "Signed-off-by: ChatGPT",
        "Signed-off-by: CHATGPT",
        "Assisted-by: Cursor <cursoragent@cursor.com>",
        "Tested-by: Gemini",
        "Co-authored-by: Devin <devin-ai-integration[bot]@users.noreply.github.com>",
        "Reviewed-by: OpenAI Codex",
        "Co-authored-by: DeepSeek",
        "Co-authored-by: Mistral Le Chat",
        "Co-authored-by: Grok",
    ] {
        let message = format!("Add gear feature\n\nBody text.\n\n{line}\n");
        let problems = check_message(&message);
        assert_eq!(problems.len(), 1, "{line}");
        let expected = format!("AI attribution in the commit message: `{line}`");
        assert!(problems[0].contains(&expected), "{problems:?}");
    }
}

// ADR-0038: a "generated with/by" note naming an AI tool is rejected.
#[test]
fn rejects_generated_by_ai() {
    for line in [
        "Generated with [Claude Code](https://claude.com/claude-code)",
        "generated by ChatGPT",
        "Code GENERATED WITH GitHub Copilot",
        "Generated by Anthropic tooling",
    ] {
        let message = format!("Add gear feature\n\n{line}\n");
        assert_eq!(check_message(&message).len(), 1, "{line}");
    }
}

// ADR-0038: the robot emoji is rejected on its own; one problem per line even
// if a line matches several rules.
#[test]
fn rejects_robot_emoji_once_per_line() {
    assert_eq!(check_message("Fix pivot 🤖\n").len(), 1);
    let message = "Add export\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n";
    assert_eq!(check_message(message).len(), 1);
}

