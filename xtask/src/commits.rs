//! Commit policy (ADR-0038, ADR-0039), run by the git hooks and in CI:
//! - no commit names an AI as author, co-author or generator,
//! - author and committer are the project identity in `harness/identity.txt`
//!   (ADR-0044),
//! - no commit changes tests and production code together, unless it says
//!   why in a `Mixed-Change:` trailer,
//! - format fixtures are never modified or deleted (ADR-0030).

use std::path::Path;

use crate::git;
use crate::paths::{self, Kind};

/// Lower-case markers of AI tools in names, e-mails and trailers.
const AI_MARKERS: &[&str] = &[
    "claude",
    "anthropic",
    "openai",
    "chatgpt",
    "gpt-",
    "copilot",
    "gemini",
    "cursoragent",
    "cursor agent",
    "cursor.com",
    "codeium",
    "windsurf",
    "tabnine",
    "devin-ai",
    "aider",
    "codex",
    "codewhisperer",
    "amazon q",
    "deepseek",
    "mistral",
    "grok",
];
pub(crate) const MIXED_TRAILER: &str = "Mixed-Change:";
/// The only identity allowed as author and committer (ADR-0044).
pub(crate) const IDENTITY_FILE: &str = "harness/identity.txt";

/// Problems in a commit message (without the commit hash prefix).
pub(crate) fn check_message(message: &str) -> Vec<String> {
    let mut problems = Vec::new();
    for line in message.lines() {
        let lower = line.trim().to_lowercase();
        let names_ai = || AI_MARKERS.iter().any(|m| lower.contains(m));
        let is_by_trailer = lower
            .split_once(':')
            .is_some_and(|(key, _)| key.ends_with("-by") && !key.contains(' '));
        let is_generated_note = lower.contains("generated with") || lower.contains("generated by");
        if lower.contains('🤖') || ((is_by_trailer || is_generated_note) && names_ai()) {
            problems.push(format!("AI attribution in the commit message: `{}`", line.trim()));
        }
    }
    problems
}

/// First non-comment, non-empty line, trimmed.
pub(crate) fn allowed_identity(text: &str) -> Option<String> {
    text.lines().map(str::trim).find(|l| !l.is_empty() && !l.starts_with('#')).map(str::to_owned)
}

/// Problems with an author/committer identity `Name <mail>`; `role` is "author" or "committer".
pub(crate) fn check_identity(role: &str, identity: &str, allowed: &str) -> Vec<String> {
    let mut problems = Vec::new();
    let lower = identity.to_lowercase();
    if AI_MARKERS.iter().any(|m| lower.contains(m)) {
        problems.push(format!("{role} `{identity}` is an AI tool"));
    }
    if identity.trim() != allowed.trim() {
        problems.push(format!(
            "{role} `{identity}` is not the project identity `{allowed}` ({IDENTITY_FILE}, ADR-0044)"
        ));
    }
    problems
}

/// `Name <mail> 1700000000 +0200` (git var GIT_AUTHOR_IDENT) → `Name <mail>`.
pub(crate) fn ident_name_email(ident: &str) -> &str {
    ident.rfind('>').map_or(ident, |end| &ident[..=end])
}

/// The allowed identity from `harness/identity.txt` in `root`.
pub(crate) fn read_allowed_identity(root: &Path) -> Result<String, String> {
    std::fs::read_to_string(root.join(IDENTITY_FILE))
        .ok()
        .and_then(|text| allowed_identity(&text))
        .ok_or_else(|| format!("{IDENTITY_FILE}: no allowed identity"))
}

/// Problems with the files of one commit: `(status, path)` pairs as printed by
/// `git diff-tree --name-status` ([`parse_name_status`]; renames contribute both
/// paths).
pub(crate) fn check_files(files: &[(String, String)], message: &str) -> Vec<String> {
    let mut problems = Vec::new();
    let kinds: Vec<Kind> = files.iter().map(|(_, p)| paths::kind(p)).collect();
    let mixed = kinds.contains(&Kind::Test) && kinds.contains(&Kind::Code);
    if mixed && !message.lines().any(|l| l.starts_with(MIXED_TRAILER)) {
        problems.push(format!(
            "changes tests and production code together (ADR-0039). Commit them separately \
             or give the reason in a `{MIXED_TRAILER} <reason>` trailer"
        ));
    }
    for (status, path) in files {
        if path.starts_with(paths::FIXTURES) && !status.starts_with('A') {
            problems.push(format!("fixture {path} modified/deleted – forbidden (ADR-0030)"));
        }
    }
    problems
}

/// Author and committer of the commit being created (commit-msg hook).
pub(crate) fn check_current_identity(root: &Path) -> Vec<String> {
    let allowed = match read_allowed_identity(root) {
        Ok(allowed) => allowed,
        Err(e) => return vec![e],
    };
    let mut problems = Vec::new();
    for (role, var) in [("author", "GIT_AUTHOR_IDENT"), ("committer", "GIT_COMMITTER_IDENT")] {
        match git(root, &["var", var]) {
            Ok(ident) => {
                problems.extend(check_identity(role, ident_name_email(ident.trim()), &allowed));
            }
            Err(e) => problems.push(e),
        }
    }
    problems
}

/// Checks every non-merge commit selected by `rev_list_args` (e.g. `main..HEAD`).
pub(crate) fn check_range(root: &Path, rev_list_args: &[String]) -> Result<(), Vec<String>> {
    let mut args = vec!["rev-list", "--no-merges", "--reverse"];
    args.extend(rev_list_args.iter().map(String::as_str));
    let allowed = read_allowed_identity(root).map_err(|e| vec![e])?;
    let shas = git(root, &args).map_err(|e| vec![e])?;
    let mut problems = Vec::new();
    for sha in shas.lines() {
        let short = &sha[..sha.len().min(10)];
        let meta = git(root, &["log", "-1", "--format=%an <%ae>%n%cn <%ce>%n%B", sha])
            .map_err(|e| vec![e])?;
        let mut lines = meta.splitn(3, '\n');
        let author = lines.next().unwrap_or_default();
        let committer = lines.next().unwrap_or_default();
        let message = lines.next().unwrap_or_default();
        // `-z`: paths unquoted, as they are (git quotes non-ASCII, tab, `"`, `\`).
        let args =
            ["diff-tree", "--root", "--no-commit-id", "-r", "--name-status", "-M", "-z", sha];
        let listing = git(root, &args).map_err(|e| vec![e])?;
        let files = parse_name_status(&listing);

        let found = check_identity("author", author, &allowed)
            .into_iter()
            .chain(check_identity("committer", committer, &allowed))
            .chain(check_message(message))
            .chain(check_files(&files, message));
        problems.extend(found.map(|p| format!("{short}: {p}")));
    }
    if problems.is_empty() { Ok(()) } else { Err(problems) }
}

/// `(status, path)` per path of a `--name-status` listing; a rename or copy
/// (`R100`, `C75`) contributes both paths. With `-z` every field ends with a
/// NUL (`M\0path\0R100\0old\0new\0`) and paths may hold tabs and newlines;
/// without, fields end with a tab or newline (`M\tpath\nR100\told\tnew\n`).
pub(crate) fn parse_name_status(listing: &str) -> Vec<(String, String)> {
    let fields: Vec<&str> = if listing.contains('\0') {
        listing.split('\0').collect()
    } else {
        listing.split(['\t', '\n']).collect()
    };
    let mut fields = fields.into_iter().filter(|f| !f.is_empty());
    let mut files = Vec::new();
    while let Some(status) = fields.next() {
        let paths = if status.starts_with(['R', 'C']) { 2 } else { 1 };
        files.extend(fields.by_ref().take(paths).map(|p| (status.to_owned(), p.to_owned())));
    }
    files
}

